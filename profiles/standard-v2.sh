#!/bin/bash
# profile-standard-v2  （凍結日 2026-11-04）
#
# standard-v1 からの変更は2点だけ。黒レベル・ノイズ処理・符号化は一切同じ。
#   (1) 切り出しを crop=704:480:28:4 → crop=746:480:4:4 に修正（下記）
#   (2) tmcd(QuickTimeタイムコードトラック)を書かない
#
# tape01/03/04/05 の4本で検証し採用。画角の実測は GV-USB2 比で
# v1 が 1.061 倍（6%太い）、v2 が 1.009 倍。15項目の自動検査は全て合格。
# このファイルは変更しない。設定を変えるときは v3 を作って別途検証する。
#
# --- (1) なぜ切り出しを変えるか ---------------------------------------
# v1 は「760x488 の出力から有効画面 704x480 を取る」としていた。これは
# BT.601 の「720サンプル中704が有効画面」という話を、サンプリング周波数の
# 違う vhs-decode の出力(760サンプル = 4fsc 14.318MHz)にそのまま当てはめた
# 誤りだった。760 は既に有効走査ほぼ全体である。
#
# 実測（tape04、9か所×20コマの列平均、2026-11-04）:
#   参照(GV-USB2) 720幅 … 画のある範囲 x=7〜710  幅704
#   マスター      760幅 … 画のある範囲 x=2〜749  幅748
#   参照の1画素はマスターの1.0610画素（5か所で相関0.994〜0.9994）
#   縦は倍率1.000・オフセット+4 で、v1 の crop の縦指定は正しい
#   両者の端の落ち込みの形は一致 → テープ側のもので、デコードの癖ではない
#
# 理屈とも合う。NTSCの有効走査 52.66us を 4fsc で数えると 754サンプル。
# 実測748との差はVHSの端の落ち込みぶん。704では足りない。
#
# v1 の影響: 横の 5.9% を捨て、残りを4:3に引き伸ばしていたため、画が横に
# 748/704 = 約1.06倍 太っていた。
#
# v2 の 746@4 は、GV-USB2 が見せている範囲(x=7〜710)をマスター座標に
# 載せ替えた 2.7〜748.6 とほぼ一致する。つまり従来の見え方と同じ画角になる。
# ----------------------------------------------------------------------

PROFILE_NAME="standard-v2"
# 2026-11-04 採用。v1 の納品物は全て v2 で作り直し、削除済み。
PROFILE_LABEL="標準"

# --- 黒レベル ---（v1 と同じ）
# 書き出しはフルレンジ(黒=0 白=1023)。68 は全編ヒストグラムの下位0.5%付近。
BLACK=68

# --- ノイズ処理 ---（v1 と同じ）
NR="hqdn3d=2:1:4:4"

# --- 映像 ---
# インタレース解除は send_field（59.94fps化）。VHSの動きの滑らかさを保つ。
# 切り出しは 760x488 の出力から有効走査 746x480 を取り、4:3 の 640x480 へ。
# フル→リミテッド変換をここで行う。大半のプレーヤーはタグを見ないため、
# 納品物は確実に表示される符号化にしておく。
DEINTERLACE="bwdif=mode=send_field:parity=tff"
CROP="crop=746:480:4:4"
SCALE="scale=640:480:flags=lanczos:in_range=pc:out_range=tv,setsar=1"

# --- 符号化 ---（v1 と同じ。MUXOPT にのみ -write_tmcd 0 を追加）
VCODEC=(-c:v libx264 -crf 18 -preset slow -pix_fmt yuv420p)
VTAGS=(-color_range tv -colorspace smpte170m -color_primaries smpte170m -color_trc smpte170m)
ACODEC=(-c:a aac -b:a 192k)
# --- (2) tmcd ---
# マスターが TAG:TIMECODE=00:00:00:00 を持つため、ffmpeg が mp4 に
# データトラック tmcd を自動で足していた。納品にタイムコードは不要。
# 画素には一切影響しない。
MUXOPT=(-movflags +faststart -write_tmcd 0)
