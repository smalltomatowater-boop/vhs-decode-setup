#!/bin/bash
# profile-standard-v6  （2026-11-14）
#
# ★ 7.5 IRE 時代のマスター専用（RF も TBC も消えていて作り直せないもの）。
#   0 IRE マスターには v5 を使うこと。vhsdeliver が止める。
#
# standard-v2 からの変更は黒点だけ。切り出し・ノイズ処理・符号化は同一。
#
# --- なぜ黒点が変わるか ---------------------------------------------
# v2 までのマスターは --NTSCJ を付けずにデコードしていたため、米国式の
# 7.5 IRE セットアップが前提になっていた。日本のテープの黒は 0 IRE なので、
# 0〜7.5 IRE の帯が書き出しの時点で切り捨てられていた。
# 詳細は docs/verify-ntscj-0ire.md。
#
# 0 IRE のマスターでは、書き出し後の値 4 がそのまま 0 IRE ＝ 真の黒である。
# つまり BLACK=4 は「テープにあったものを一切捨てない」設定で、
# 0 IRE → 映像の黒(16)、100 IRE → 白(235) という素直な変換になる。
#
# 実測（tape05、全編685コマ 0.25G画素、等倍）:
#   床(値4)に張り付いた画素  7.5IREマスター 14.61% / 0IREマスター 11.45%
#   真っ黒リードイン20コマ    7.5IRE は 100% 床に張り付く（ノイズの粒まで
#   潰れている）。0IRE は 89.8%、99%点が値14 ＝ 粒が信号として残る
#
# v2 の BLACK=68 は、潰れた画素を床のぶんも含めて 16.67% にしていた。
# BLACK=4 では 11.45%、つまりマスターが持っている情報は全部通る。
#
# 見た目は v2 より明るく、コントラストは浅くなる。暗部のノイズも見える。
# 「見栄え」が欲しい顧客には contrast-v4 を渡すこと。
# ----------------------------------------------------------------------
PROFILE_NAME="standard-v6"
# 2026-11-13 新設。0 IRE マスター用。横を縮めない（v4 との違いはそこだけ）。
PROFILE_LABEL="標準"

# --- 黒レベル ---
# 37 = 0.0 IRE ＝ 映像の黒そのもの。絵を見て決めた値ではなく、
# デコードが書き残した3つの数字から逆算した位置である。
#
#   blanking16bIre 15360.0   本物の 0 IRE（level_adjust がかからない）
#   black16bIre    16243.2 = (15360 + 7.5*358.4) * (1 - 0.1)
#   white16bIre    56320.0 = (15360 + 100*358.4) * (1 + 0.1)
#     → 1 IRE = 358.4、level_adjust = 0.1
#
# 書き出しは black16bIre→0、white16bIre→1023 に写す。--NTSCJ では
# black16bIre = 15360*0.9 = 13824 なので、目盛りはこうなる:
#
#     値  37 =   0.0 IRE   映像の黒 ← ここ
#     値 102 =   7.5 IRE   米国式セットアップ
#     値 122 =   9.9 IRE   standard-v2 の黒点68 と同じ見た目
#     値 137 =  11.6 IRE   contrast-v2 の黒点84 と同じ見た目
#     値 900 = 100.0 IRE   白（実測の最大 894 と一致）
#
# standard-v2 は黒より 9.9 IRE 上まで切り捨てていた。
# このプロファイルは 0 IRE より上を一切捨てない。
MASTER_BLACK_IRE=7.5
BLACK=37   # 使われない。LUTYUV が優先される（下記）

# --- 7.5 IRE マスターを 0 IRE 相当に直してから黒点を当てる ---
# --NTSCJ 漏れの誤りは信号全体の一次変換だった（docs/verify-ntscj-0ire.md）:
#     out_0ire = 0.9431 × out_7.5 + 58.24
#     輝度も色差も同じ比率（実測 Y 0.9431 / U 0.9430 / V 0.9428）
# これに v5 の黒点 37 を合成すると、輝度は一次式1本にまとまる:
#     y = 0.97849 × val + 22.037
# 色差は 512 を中心に 0.9431 倍する。v5 までの納品物は 1/0.9431 = 6.03%
# 色が濃すぎた。納品に彩度のつまみが無いので黒点では戻せず、ここで直す。
#
# **戻らないもの:** 7.5 IRE の書き出しで床に潰れた暗部。
# マスターの時点で失われており、一次変換では復元できない。
LUTYUV="lutyuv=y='clip(0.97849*val+22.037,0,1023)':u='clip((val-512)*0.9431+512,0,1023)':v='clip((val-512)*0.9431+512,0,1023)'"

# --- ノイズ処理 ---（v1 と同じ）
NR="hqdn3d=2:1:4:4"

# --- 映像 ---
# インタレース解除は send_field（59.94fps化）。VHSの動きの滑らかさを保つ。
# 切り出しは 760x488 の出力から有効走査 746x480 を取り、4:3 の 640x480 へ。
# フル→リミテッド変換をここで行う。大半のプレーヤーはタグを見ないため、
# 納品物は確実に表示される符号化にしておく。
DEINTERLACE="bwdif=mode=send_field:parity=tff"
# 切り出しの位置と高さを実測で決め直した（tape05・120コマ平均、
# それぞれの端の近くを基準にした相対値）:
#   左   x=0 89.7%  x=1 95.9%  x=2 99.4%  x=3 101.4%
#   右   x=746 94.9%  x=747 92.3%  x=748 88.8%  x=749 84.6%  x=752 67.3%
#   上   y=0,1 床   y=2 62.6%  y=3 67.1%  y=4 96.4%  y=5 99.8%
#   下   y=479 95.9%  y=480〜485 約73%（ヘッド切替の帯）  y=487 床
# v4 までの 746:480:4:4 は右に3画素ずれていて、右端の薄い3列を拾い、
# 左の良い3列を捨てていた。下はヘッド切替の帯を4行ぶん含んでいた。
# ここでは残る画素が全て 95.9% 以上になる窓を取る。
CROP="crop=746:476:1:4"
# 横は縮めない。746 のまま出し、画素比で 4:3 にする。
#   746 × 6/7 = 639.43 正方画素。高さ476 → 表示比 1.34334
# 746 という幅は恣意的ではない。BT.601 の有効画面 704標本@13.5MHz は
# 52.1481us で、同じ時間を 4fsc(14.318MHz) で数えると 746.67 標本になる。
# つまり 640(正方画素) = 704(13.5MHz) = 746(4fsc) は全て同じ横幅であり、
# 画素の大きさが違うだけ。マスターの760標本は 716.6@13.5MHz ≒ 717 で、
# 746 との差14標本がブラウン管で見えなかった余白にあたる。
# 4:3 より僅かに平たいのは、下のヘッド切替の帯を削ったぶん縦が
# 減っているため。これが正しい。
# scale は大きさを変えず、フルレンジ→リミテッドの変換だけを担う。
#
# なぜ縮めるのをやめたか（2026-11-13 実測、tape05 の64コマ）:
#   有効走査746画素=52.66us として横方向のスペクトルを取ると
#     3.00MHz(158サイクル) 以上  0.416%   ← VHSの輝度帯域の上限
#     6.08MHz(320サイクル) 以上  0.0177%  ← 640 に縮めると落ちる範囲
#   つまり落ちるのは -46dB のノイズで、絵ではない。
#   「縮めても失われない」ことは確かめられたが、**縮める理由が無い**。
#   画角は crop で決まっており、640 でも 746 でも映る範囲は同一。
#   変わるのは横の再標本化を通すかどうかだけ。通さない方を選ぶ。
# 画素比 6:7 は 4fsc(14.318MHz) 格子の正確な値。
#   4fsc / 13.5MHz = 35/33
#   13.5MHz の画素比 10:11 × 33/35 = 6/7   （ぴったり約分できる）
# 一時 320:373 を使っていたが、あれは「746標本をちょうど4:3と見なす」
# 近似で、0.0894% 横に広かった。746 の正確な値は 746.67 標本である。
#
# setsar に分母の大きい値を渡すときは max を付けること。既定は 100 で、
# 320/373 は 85:99 に丸められた（実測で踏んだ）。6:7 は丸められない。
SCALE="scale=746:476:in_range=pc:out_range=tv,setsar=6/7"

# --- 符号化 ---（v1 と同じ。MUXOPT にのみ -write_tmcd 0 を追加）
VCODEC=(-c:v libx264 -crf 18 -preset slow -pix_fmt yuv420p)
VTAGS=(-color_range tv -colorspace smpte170m -color_primaries smpte170m -color_trc smpte170m)
ACODEC=(-c:a aac -b:a 192k)
# --- (2) tmcd ---
# マスターが TAG:TIMECODE=00:00:00:00 を持つため、ffmpeg が mp4 に
# データトラック tmcd を自動で足していた。納品にタイムコードは不要。
# 画素には一切影響しない。
MUXOPT=(-movflags +faststart -write_tmcd 0)
