#!/bin/bash
# profile-contrast-v3  （凍結日 2026-11-12）
#
# v2 からの変更は1点だけ。黒レベル・切り出し・倍率・符号化は一切同じ。
#   (3) 白飛び場面で出る虹色ノイズの区間だけ、色を抜く（下記）
#
# --- (3) なぜ色を抜くか -----------------------------------------------
# 2026-11-12、マスターが tape05 の納品物に乱れを見つけた。調べると原因は
# テープでもデッキでもなく、うちのRF経路だった。白飛びするフラッシュ場面で、
# デッキのS端子出力はきれいな白のままなのに、vhs-decode は色を増幅して
# 虹色のゴミを出す。デッキには色が無いときに色を切る回路があり、
# vhs-decode には無い。
#
#   --chroma-decoder を ntsc3d → ntsc2d にしても結果は同一（色差σで
#   S端子から8以上ずれたコマが 10個 対 10個）。よって色の復号段ではなく、
#   その手前のRFからの色の取り出し段の問題。ここでは直せないので納品段で消す。
#
# 消してよい理由: 該当区間は元々ほぼ白で、本来の色がほとんど無い。
# S端子側の実測でも色差σは 0.5〜6.9 しかない。虹色は全て偽の色。
#
# tape05r での実測（2026-11-12）:
#   区間 18件 / 計45.4秒 / 本編457秒の 9.93%
#   修正前 σ 24〜38 → 修正後 0.00、正常部は値が1つも動かない
#
# 区間は本ごとに違うので、プロファイルには入れずに
# VHS_CHROMA_JSON が指すファイルから読む（bin/vhschroma.py が作る）。
# 指定が無い／ファイルが無いときは止める。黙って未修復を納品しないため。
# ----------------------------------------------------------------------
#
# contrast-v1 からの変更は2点。黒レベル・ノイズ処理・符号化は v1 と同じ。
#   (1) 切り出しを crop=704:480:28:4 → crop=746:480:4:4 に修正（下記）
#   (2) tmcd(QuickTimeタイムコードトラック)を書かない
#
# tape01/03/04/05 の4本で検証し採用。画角の実測は GV-USB2 比で
# v1 が 1.061 倍（6%太い）、v2 が 1.009 倍。15項目の自動検査は全て合格。
# このファイルは変更しない。設定を変えるときは v4 を作って別途検証する。
#
# --- (1) なぜ切り出しを変えるか ---------------------------------------
# v1 は「760x488 の出力から有効画面 704x480 を取る」としていた。これは
# BT.601 の「720サンプル中704が有効画面」という話を、サンプリング周波数の
# 違う vhs-decode の出力(760サンプル = 4fsc 14.318MHz)にそのまま当てはめた
# 誤りだった。760 は既に有効走査ほぼ全体である。
#
# 実測（tape04、9か所×20コマの列平均、2026-11-04）:
#   参照(GV-USB2) 720幅 … 画のある範囲 x=7〜710  幅704
#   マスター      760幅 … 画のある範囲 x=2〜749  幅748
#   参照の1画素はマスターの1.0610画素（5か所で相関0.994〜0.9994）
#   縦は倍率1.000・オフセット+4 で、v1 の crop の縦指定は正しい
#   両者の端の落ち込みの形は一致 → テープ側のもので、デコードの癖ではない
#
# 理屈とも合う。NTSCの有効走査 52.66us を 4fsc で数えると 754サンプル。
# 実測748との差はVHSの端の落ち込みぶん。704では足りない。
#
# v1 の影響: 横の 5.9% を捨て、残りを4:3に引き伸ばしていたため、画が横に
# 748/704 = 約1.06倍 太っていた。
#
# v2 の 746@4 は、GV-USB2 が見せている範囲(x=7〜710)をマスター座標に
# 載せ替えた 2.7〜748.6 とほぼ一致する。つまり従来の見え方と同じ画角になる。
# ----------------------------------------------------------------------

PROFILE_NAME="contrast-v3"
# 2026-11-04 採用。v1 の納品物は全て v2 で作り直し、削除済み。
PROFILE_LABEL="コントラスト重視"

# --- 黒レベル ---（v1 と同じ）
# 見栄え重視。84 は黒い被写体のある場面で潰れた画素の17〜26%が
# 10画素以上の連続構造になる。情報保持より見栄えを選ぶ顧客向け。
BLACK=84

# --- ノイズ処理 ---（v1 と同じ）
NR="hqdn3d=2:1:4:4"

# --- 色ノイズの修復（v3で追加） ---
# フィルタ順の都合でここに入れる。vhsdeliver は VF を
#   DEINTERLACE,CROP,lutyuv,NR,SCALE
# の順で組み立てるため、NR の前に差し込むと切り出しの後・縮小の前になる。
# hue=s=0 は該当区間の彩度を0にするだけで、輝度には一切触れない。
if [ -z "${VHS_CHROMA_JSON:-}" ]; then
  echo "${PROFILE_NAME}: VHS_CHROMA_JSON が未設定。v3 は色修復が前提なので止める" >&2
  echo "  先に: bin/vhschroma.py <映像> --out <作業場>/chroma_mute.json" >&2
  exit 1
fi
if [ ! -f "$VHS_CHROMA_JSON" ]; then
  echo "${PROFILE_NAME}: 色修復の区間ファイルが無い: $VHS_CHROMA_JSON" >&2
  exit 1
fi
_CHROMA_EXPR=$("${VHS_PY:-python3}" -c 'import json,sys; print(json.load(open(sys.argv[1]))["enable"])' "$VHS_CHROMA_JSON") || {
  echo "${PROFILE_NAME}: 区間ファイルを読めない: $VHS_CHROMA_JSON" >&2; exit 1; }
if [ -n "$_CHROMA_EXPR" ] && [ "$_CHROMA_EXPR" != "0" ]; then
  NR="hue=s=0:enable='${_CHROMA_EXPR}',${NR}"
  echo "  色修復: $VHS_CHROMA_JSON の区間で彩度を0にする"
else
  echo "  色修復: 該当区間なし（素通し）"
fi

# --- 映像 ---
# インタレース解除は send_field（59.94fps化）。VHSの動きの滑らかさを保つ。
# 切り出しは 760x488 の出力から有効走査 746x480 を取り、4:3 の 640x480 へ。
# フル→リミテッド変換をここで行う。大半のプレーヤーはタグを見ないため、
# 納品物は確実に表示される符号化にしておく。
DEINTERLACE="bwdif=mode=send_field:parity=tff"
CROP="crop=746:480:4:4"
SCALE="scale=640:480:flags=lanczos:in_range=pc:out_range=tv,setsar=1"

# --- 符号化 ---（v1 と同じ。MUXOPT にのみ -write_tmcd 0 を追加）
VCODEC=(-c:v libx264 -crf 18 -preset slow -pix_fmt yuv420p)
VTAGS=(-color_range tv -colorspace smpte170m -color_primaries smpte170m -color_trc smpte170m)
ACODEC=(-c:a aac -b:a 192k)
# --- (2) tmcd ---
# マスターが TAG:TIMECODE=00:00:00:00 を持つため、ffmpeg が mp4 に
# データトラック tmcd を自動で足していた。納品にタイムコードは不要。
# 画素には一切影響しない。
MUXOPT=(-movflags +faststart -write_tmcd 0)
