#!/bin/bash
# profile-contrast-v7  （2026-11-19）
#
# contrast-v5 に「色の濃さ 1.45 倍」を足しただけ。黒点 137・切り出し・
# ノイズ処理・符号化は v5 と同一。標準版(standard-v5)は触らない。
#
# --- なぜ 1.45 か ---
# VHS-Decode は記録されたままを出すので、従来のキャプチャ（デッキや
# 機器が彩度を強調している）より淡く見える。実測の一例では彩度が約 2/3。
# 保存マスターは触らず、納品用 mp4 の段階で色差(U/V)を 512 から 1.45 倍
# 離す。1.00 / 1.30 / 1.45 を tape05 の10場面で並べ、1.30 は
# 「わかりづらい」ため 1.45 に決めた（2026-11-19、マスターの決定）。
# 実測: 明るい側の飽和 0%。暗くない画素の RGB がマイナスに切られる割合は
# 最悪の場面で 0.6%。色ノイズは 1.45 倍。
# 色のノイズも同じ倍率で増えるので、NR は掛け算のあとに置いてある。
#
# ★ 0 IRE マスター専用（v5 と同じ）。
#
# ★ 0 IRE マスター専用。7.5 IRE 時代のマスターには使えない。
#   vhsdeliver が mkv の VHS_BLACK_IRE タグと突き合わせて止める。
#
# contrast-v2 からの変更は黒点だけ。切り出し・ノイズ処理・符号化は同一。
#
# --- なぜ 137 か -----------------------------------------------------
# マスターの黒レベルを 0 IRE に直したことで、書き出し後の値が
#   out_new = 0.9431 × out_old + 58.24
# だけずれた（信号全体の一次変換。詳細は docs/verify-ntscj-0ire.md）。
# v2 の BLACK=84 をこの式に通すと 137.5 になる。
#
# つまり **見た目は contrast-v2 と同じ**。これまで納品した6本と並べても
# 違和感が出ない。変わるのは色が 6.0% 薄くなること（v2 までが
# 濃すぎた。同じ 0.9431 倍が色差にもかかっていた）と、
# 暗部の情報がマスター側に残っていること。
#
# 実測（tape05 全編）: 潰れる画素は v2 が 17.19%、このプロファイルが 17.37%。
# ほぼ同じ。見栄えの設計はそのまま引き継いでいる。
#
# 情報を捨てたくない顧客には standard-v4（BLACK=4）を渡すこと。
# ----------------------------------------------------------------------
PROFILE_NAME="contrast-v7"
# 2026-11-13 新設。0 IRE マスター用。横を縮めない（v4 との違いはそこだけ）。contrast-v2 と同じ見た目。
PROFILE_LABEL="コントラスト重視"

# --- 黒レベル ---
# 見栄え重視。contrast-v2 の 84 を 0 IRE 目盛りに載せ替えた値。
# 情報保持より見栄えを選ぶ顧客向け。
MASTER_BLACK_IRE=0
BLACK=137   # LUTYUV の中の y に使う値と同じ

# --- 輝度は v5 と同じ黒点、色差だけ 1.45 倍 ---
# 10bit の値で 512 が無彩色。(val-512)*SAT+512 は彩度を SAT 倍にする。
SAT=1.45
LUTYUV="lutyuv=y='clip((val-$BLACK)*1023/(1023-$BLACK),0,1023)':u='clip((val-512)*$SAT+512,0,1023)':v='clip((val-512)*$SAT+512,0,1023)'"

# --- ノイズ処理 ---（v1 と同じ）
NR="hqdn3d=2:1:4:4"

# --- 映像 ---
# インタレース解除は send_field（59.94fps化）。VHSの動きの滑らかさを保つ。
# 切り出しは 760x488 の出力から有効走査 746x480 を取り、4:3 の 640x480 へ。
# フル→リミテッド変換をここで行う。大半のプレーヤーはタグを見ないため、
# 納品物は確実に表示される符号化にしておく。
DEINTERLACE="bwdif=mode=send_field:parity=tff"
# 切り出しの位置と高さを実測で決め直した（tape05・120コマ平均、
# それぞれの端の近くを基準にした相対値）:
#   左   x=0 89.7%  x=1 95.9%  x=2 99.4%  x=3 101.4%
#   右   x=746 94.9%  x=747 92.3%  x=748 88.8%  x=749 84.6%  x=752 67.3%
#   上   y=0,1 床   y=2 62.6%  y=3 67.1%  y=4 96.4%  y=5 99.8%
#   下   y=479 95.9%  y=480〜485 約73%（ヘッド切替の帯）  y=487 床
# v4 までの 746:480:4:4 は右に3画素ずれていて、右端の薄い3列を拾い、
# 左の良い3列を捨てていた。下はヘッド切替の帯を4行ぶん含んでいた。
# ここでは残る画素が全て 95.9% 以上になる窓を取る。
CROP="crop=746:476:1:4"
# 横は縮めない。746 のまま出し、画素比で 4:3 にする。
#   746 × 6/7 = 639.43 正方画素。高さ476 → 表示比 1.34334
# 746 という幅は恣意的ではない。BT.601 の有効画面 704標本@13.5MHz は
# 52.1481us で、同じ時間を 4fsc(14.318MHz) で数えると 746.67 標本になる。
# つまり 640(正方画素) = 704(13.5MHz) = 746(4fsc) は全て同じ横幅であり、
# 画素の大きさが違うだけ。マスターの760標本は 716.6@13.5MHz ≒ 717 で、
# 746 との差14標本がブラウン管で見えなかった余白にあたる。
# 4:3 より僅かに平たいのは、下のヘッド切替の帯を削ったぶん縦が
# 減っているため。これが正しい。
# scale は大きさを変えず、フルレンジ→リミテッドの変換だけを担う。
#
# なぜ縮めるのをやめたか（2026-11-13 実測、tape05 の64コマ）:
#   有効走査746画素=52.66us として横方向のスペクトルを取ると
#     3.00MHz(158サイクル) 以上  0.416%   ← VHSの輝度帯域の上限
#     6.08MHz(320サイクル) 以上  0.0177%  ← 640 に縮めると落ちる範囲
#   つまり落ちるのは -46dB のノイズで、絵ではない。
#   「縮めても失われない」ことは確かめられたが、**縮める理由が無い**。
#   画角は crop で決まっており、640 でも 746 でも映る範囲は同一。
#   変わるのは横の再標本化を通すかどうかだけ。通さない方を選ぶ。
# 画素比 6:7 は 4fsc(14.318MHz) 格子の正確な値。
#   4fsc / 13.5MHz = 35/33
#   13.5MHz の画素比 10:11 × 33/35 = 6/7   （ぴったり約分できる）
# 一時 320:373 を使っていたが、あれは「746標本をちょうど4:3と見なす」
# 近似で、0.0894% 横に広かった。746 の正確な値は 746.67 標本である。
#
# setsar に分母の大きい値を渡すときは max を付けること。既定は 100 で、
# 320/373 は 85:99 に丸められた（実測で踏んだ）。6:7 は丸められない。
SCALE="scale=746:476:in_range=pc:out_range=tv,setsar=6/7"

# --- 符号化 ---（v1 と同じ。MUXOPT にのみ -write_tmcd 0 を追加）
VCODEC=(-c:v libx264 -crf 18 -preset slow -pix_fmt yuv420p)
VTAGS=(-color_range tv -colorspace smpte170m -color_primaries smpte170m -color_trc smpte170m)
ACODEC=(-c:a aac -b:a 192k)
# --- (2) tmcd ---
# マスターが TAG:TIMECODE=00:00:00:00 を持つため、ffmpeg が mp4 に
# データトラック tmcd を自動で足していた。納品にタイムコードは不要。
# 画素には一切影響しない。
MUXOPT=(-movflags +faststart -write_tmcd 0)
